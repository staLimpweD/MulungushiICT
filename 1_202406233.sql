-- ---- Task 2: IF ELSIF ELSE on copy availability ----
DO $$
DECLARE
    v_copies integer;
BEGIN
    SELECT available_copies INTO v_copies
    FROM books WHERE book_id = 2;

    IF v_copies = 0 THEN
        RAISE NOTICE 'Book unavailable';
    ELSIF v_copies <= 1 THEN
        RAISE NOTICE 'Book low on copies: % remaining', v_copies;
    ELSE
        RAISE NOTICE 'Book sufficiently stocked: % remaining', v_copies;
    END IF;
END;
$$ LANGUAGE plpgsql;
-- Expected message: "Book low on copies: 1 remaining"

-- ---- Task 3: WHILE loop (overdue reminders) and FOR loop (shelf numbers) ----
DO $$
DECLARE
    v_reminder integer := 1;
BEGIN
    WHILE v_reminder <= 3 LOOP
        RAISE NOTICE 'Overdue reminder #%', v_reminder;
        v_reminder := v_reminder + 1;
    END LOOP;

    FOR v_shelf IN 1..3 LOOP
        RAISE NOTICE 'Checking shelf number %', v_shelf;
    END LOOP;
END;
$$ LANGUAGE plpgsql;
-- Expected: 3 overdue reminder notices, then 3 shelf-number notices

-- ---- Task 4: borrow_book procedure ----
CREATE OR REPLACE PROCEDURE borrow_book(
    p_book_id        integer,
    p_student_number text,
    p_quantity       integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_loan_id   integer;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT available_copies INTO v_available
    FROM books
    WHERE book_id = p_book_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Book % does not exist', p_book_id;
        RETURN;
    ELSIF v_available < p_quantity THEN
        RAISE NOTICE 'Insufficient copies: only % available', v_available;
        RETURN;
    END IF;

    UPDATE books
    SET available_copies = available_copies - p_quantity
    WHERE book_id = p_book_id;

    INSERT INTO book_loans (book_id, student_number, quantity, status)
    VALUES (p_book_id, p_student_number, p_quantity, 'ACTIVE')
    RETURNING loan_id INTO v_loan_id;

    RAISE NOTICE 'Loan % created for student %', v_loan_id, p_student_number;
END;
$$;

