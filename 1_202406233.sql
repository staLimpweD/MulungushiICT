-- ---- Task 6: return_book procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE return_book(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_book_id  integer;
    v_quantity integer;
BEGIN
    SELECT book_id, quantity
    INTO v_book_id, v_quantity
    FROM book_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE book_loans
    SET status = 'RETURNED'
    WHERE loan_id = p_loan_id;

    UPDATE books
    SET available_copies = available_copies + v_quantity
    WHERE book_id = v_book_id;

    RAISE NOTICE 'Loan % returned; % copies restored', p_loan_id, v_quantity;
END;
$$;

CALL return_book(1);
CALL return_book(1);   -- second call: already RETURNED, must not restore copies again
-- Expected: first call restores copies and prints confirmation;
--           second call prints "No active loan with ID 1"

-- ---- Task 7: Explicit cursor for books with few copies ----
CREATE OR REPLACE PROCEDURE show_low_stock_books()
LANGUAGE plpgsql
AS $$
DECLARE
    v_book   record;
    c_low    CURSOR FOR
        SELECT title, available_copies
        FROM books
        WHERE available_copies <= 2
        ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_book;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_book.title, v_book.available_copies;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_stock_books();
-- Expected: at least "Introduction to Algorithms (1 remaining)" is reported

