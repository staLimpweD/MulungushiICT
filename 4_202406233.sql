-- ---- Task 6: reverse_dispensing procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicine_id integer;
    v_quantity    integer;
BEGIN
    SELECT medicine_id, quantity
    INTO v_medicine_id, v_quantity
    FROM dispensing_records
    WHERE record_id = p_record_id AND status = 'DISPENSED'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No dispensed record with ID % to reverse', p_record_id;
        RETURN;
    END IF;

    UPDATE dispensing_records
    SET status = 'REVERSED'
    WHERE record_id = p_record_id;

    UPDATE medicines
    SET stock_quantity = stock_quantity + v_quantity
    WHERE medicine_id = v_medicine_id;

    RAISE NOTICE 'Record % reversed; % units restored to stock', p_record_id, v_quantity;
END;
$$;

CALL reverse_dispensing(1);
CALL reverse_dispensing(1);   -- second call: already REVERSED, stock must not be restored again
-- Expected: first call restores stock and prints confirmation;
--           second call prints "No dispensed record with ID 1 to reverse"

-- ---- Task 7: Explicit cursor for medicines below the low-stock threshold ----
CREATE OR REPLACE PROCEDURE show_low_stock_medicines()
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicine  record;
    c_low       CURSOR FOR
        SELECT medicine_name, stock_quantity
        FROM medicines
        WHERE stock_quantity <= 5
        ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_medicine;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low stock: % (% remaining)', v_medicine.medicine_name, v_medicine.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_stock_medicines();
-- Expected: at least "ORS Sachets (2 remaining)" is reported

