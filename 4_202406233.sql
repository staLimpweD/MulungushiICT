-- ---- Task 2: IF ELSIF ELSE on stock level ----
DO $$
DECLARE
    v_stock integer;
BEGIN
    SELECT stock_quantity INTO v_stock
    FROM medicines WHERE medicine_id = 2;

    IF v_stock = 0 THEN
        RAISE NOTICE 'Medicine out of stock';
    ELSIF v_stock <= 2 THEN
        RAISE NOTICE 'Medicine low on stock: % remaining', v_stock;
    ELSE
        RAISE NOTICE 'Medicine sufficiently stocked: % remaining', v_stock;
    END IF;
END;
$$ LANGUAGE plpgsql;
-- Expected message: "Medicine low on stock: 2 remaining"

