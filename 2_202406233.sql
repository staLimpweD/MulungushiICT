-- ---- Task 2: IF ELSIF ELSE on session capacity ----
DO $$
DECLARE
    v_workstations integer;
BEGIN
    SELECT available_workstations INTO v_workstations
    FROM lab_sessions WHERE session_id = 2;

    IF v_workstations = 0 THEN
        RAISE NOTICE 'Session full';
    ELSIF v_workstations <= 2 THEN
        RAISE NOTICE 'Session nearly full: % workstations left', v_workstations;
    ELSE
        RAISE NOTICE 'Session has enough workstations: % left', v_workstations;
    END IF;
END;
$$ LANGUAGE plpgsql;
