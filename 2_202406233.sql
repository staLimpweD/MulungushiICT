-- ---- Task 6: cancel_reservation procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE cancel_reservation(p_reservation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_session_id   integer;
    v_workstations integer;
BEGIN
    SELECT session_id, workstations
    INTO v_session_id, v_workstations
    FROM reservations
    WHERE reservation_id = p_reservation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active reservation with ID %', p_reservation_id;
        RETURN;
    END IF;

    UPDATE reservations
    SET status = 'CANCELLED'
    WHERE reservation_id = p_reservation_id;

    UPDATE lab_sessions
    SET available_workstations = available_workstations + v_workstations
    WHERE session_id = v_session_id;

    RAISE NOTICE 'Reservation % cancelled; % workstations released', p_reservation_id, v_workstations;
END;
$$;

CALL cancel_reservation(1);
CALL cancel_reservation(1);   -- second call: already CANCELLED, must not release again
-- Expected: first call releases workstations and prints confirmation;
--           second call prints "No active reservation with ID 1"

-- ---- Task 7: Explicit cursor for sessions with few workstations ----
CREATE OR REPLACE PROCEDURE show_low_availability_sessions()
LANGUAGE plpgsql
AS $$
DECLARE
    v_session  record;
    c_low      CURSOR FOR
        SELECT session_name, available_workstations
        FROM lab_sessions
        WHERE available_workstations <= 2
        ORDER BY session_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_session;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Low availability: % (% remaining)', v_session.session_name, v_session.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$;

CALL show_low_availability_sessions();
-- Expected: at least "ICT372 Networks Practical (2 remaining)" is reported

