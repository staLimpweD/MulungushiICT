-- ---- Task 4: allocate_room procedure ----
-- Note: a hostel allocation is one bed space per student, so there is no
-- quantity parameter here (unlike the other scenarios) — only a room and a
-- student number. Availability is reduced by exactly one each call.
CREATE OR REPLACE PROCEDURE allocate_room(
    p_room_id        integer,
    p_student_number text
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available     integer;
    v_allocation_id integer;
BEGIN
    IF p_student_number IS NULL OR btrim(p_student_number) = '' THEN
        RAISE EXCEPTION 'Student number must not be blank'
            USING ERRCODE = '22023';
    END IF;

    SELECT available_spaces INTO v_available
    FROM hostel_rooms
    WHERE room_id = p_room_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Room % does not exist', p_room_id;
        RETURN;
    ELSIF v_available < 1 THEN
        RAISE NOTICE 'Room % is full: no spaces available', p_room_id;
        RETURN;
    END IF;

    UPDATE hostel_rooms
    SET available_spaces = available_spaces - 1
    WHERE room_id = p_room_id;

    INSERT INTO allocations (room_id, student_number, status)
    VALUES (p_room_id, p_student_number, 'ACTIVE')
    RETURNING allocation_id INTO v_allocation_id;

    RAISE NOTICE 'Allocation % created for student %', v_allocation_id, p_student_number;
END;
$$;

