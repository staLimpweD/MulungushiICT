-- ---- Task 6: check_out procedure (idempotent on repeat call) ----
CREATE OR REPLACE PROCEDURE check_out(p_allocation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_room_id integer;
BEGIN
    SELECT room_id
    INTO v_room_id
    FROM allocations
    WHERE allocation_id = p_allocation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active allocation with ID %', p_allocation_id;
        RETURN;
    END IF;

    UPDATE allocations
    SET status = 'CHECKED_OUT'
    WHERE allocation_id = p_allocation_id;

    UPDATE hostel_rooms
    SET available_spaces = available_spaces + 1
    WHERE room_id = v_room_id;

    RAISE NOTICE 'Allocation % checked out; 1 space released in room %', p_allocation_id, v_room_id;
END;
$$;

CALL check_out(1);
CALL check_out(1);   -- second call: already CHECKED_OUT, must not free another space
-- Expected: first call releases a space and prints confirmation;
--           second call prints "No active allocation with ID 1"

-- ---- Task 7: Explicit cursor for full or nearly full rooms ----
CREATE OR REPLACE PROCEDURE show_full_or_near_full_rooms()
LANGUAGE plpgsql
AS $$
DECLARE
    v_room  record;
    c_full  CURSOR FOR
        SELECT room_name, available_spaces
        FROM hostel_rooms
        WHERE available_spaces <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_room;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full: % (% remaining)', v_room.room_name, v_room.available_spaces;
    END LOOP;
    CLOSE c_full;
END;
$$;

CALL show_full_or_near_full_rooms();
-- Expected: at least "Block A Room 102 (0 remaining)" is reported

