-- ---- Task 2: IF ELSIF ELSE on room occupancy ----
DO $$
DECLARE
    v_spaces integer;
BEGIN
    SELECT available_spaces INTO v_spaces
    FROM hostel_rooms WHERE room_id = 2;

    IF v_spaces = 0 THEN
        RAISE NOTICE 'Room full';
    ELSIF v_spaces = 1 THEN
        RAISE NOTICE 'Room has one space left';
    ELSE
        RAISE NOTICE 'Room has several spaces: % remaining', v_spaces;
    END IF;
END;
$$ LANGUAGE plpgsql;
-- Expected message: "Room has one space left"

